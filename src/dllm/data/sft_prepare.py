def _dry_run(alloc: dict[str, dict[str, int]], langs: list[str]) -> None:
    print("[sft-prepare] dry-run: probing each source for one example per lang...")
    for src_name in alloc:
        try:
            src = sources.load(src_name)
        except ValueError as e:
            print(f"  [err] cannot load {src_name}: {e}")
            continue
        print(f"  {src_name} ({src.task_type()}):")
        for lang in langs:
            if lang not in src.supported_langs():
                print(f"    [skip] {lang}: not supported by {src_name}")
                continue
            try:
                it = src.iter_examples(lang, 1)
                conv = next(it, None)
                if conv is None:
                    print(f"    [warn] {lang}: no examples returned")
                else:
                    n_msgs = len(conv.messages)
                    n_tc = sum(len(m.tool_calls) for m in conv.messages)
                    n_chars = sum(len(m.content) for m in conv.messages)
                    print(f"    [ok]   {lang}: {n_msgs} msgs, {n_tc} tool_calls, {n_chars} chars")
            except Exception as e:  # noqa: BLE001
                print(f"    [err]  {lang}: {type(e).__name__}: {e}")
    print("[sft-prepare] dry-run done")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--langs", nargs="+", default=DEFAULT_LANGS)
    ap.add_argument("--sources", nargs="+", default=list(DEFAULT_ALLOC_COUNT),
                    choices=sources.all_source_names())
    ap.add_argument("--alloc", type=Path, default=None,
                    help="Optional JSON file overriding per-source per-lang example counts.")
    ap.add_argument("--val-fraction", type=float, default=0.02,
                    help="Fraction of conversations (by token count, conv-aligned) to hold out for val.")
    ap.add_argument("--batch-size", type=int, default=64,
                    help="Conversations per tokenize batch.")
    ap.add_argument("--dry-run", action="store_true",
                    help="Probe each source for one example; write nothing.")
    args = ap.parse_args()

    alloc = {k: dict(v) for k, v in DEFAULT_ALLOC_COUNT.items() if k in args.sources}
    if args.alloc:
        override = json.loads(args.alloc.read_text(encoding="utf-8"))
        for src_name, lang_budgets in override.items():
            if src_name in alloc:
                alloc[src_name].update(lang_budgets)
            else:
                alloc[src_name] = lang_budgets
    alloc = {s: {l: c for l, c in d.items() if l in args.langs} for s, d in alloc.items()}

    print("[sft-prepare] allocation (examples per source × lang):")
    for src_name, lang_budgets in alloc.items():
        total = sum(lang_budgets.values())
        print(f"  {src_name}: {total:,} convs across {sorted(lang_budgets)}")
    print(f"  TOTAL: {sum(sum(d.values()) for d in alloc.values()):,} target conversations")

    if args.dry_run:
        _dry_run(alloc, args.langs)
        return

    tok_path = pretrain_tokenizer_path()
    if not tok_path.exists():
        sys.exit(
            f"[sft-prepare] FATAL: pretraining tokenizer not found at {tok_path}\n"
            "Run `python -m dllm.data.prepare` first (or --reuse-tokenizer with an existing one)."
        )

    from tokenizers import Tokenizer  # noqa: PLC0415
    tokenizer = Tokenizer.from_file(str(tok_path))
    vocab_size = tokenizer.get_vocab_size()
    print(f"[sft-prepare] loaded pretrain tokenizer (vocab_size={vocab_size})")

    out = cache_dir()
    print(f"[sft-prepare] output dir: {out}")
    train_ids = out / "sft_train.bin"
    train_mask = out / "sft_train_mask.bin"
    val_ids = out / "sft_val.bin"
    val_mask = out / "sft_val_mask.bin"
    for p in (train_ids, train_mask, val_ids, val_mask):
        if p.exists():
            p.unlink()

    print("[sft-prepare] tokenize: parallel producers → encode_batch → disk")
    total_tokens, per_pair, boundaries = stream_tokenize_to_disk(
        alloc, args.langs, tokenizer, train_ids, train_mask,
        batch_size=args.batch_size,
    )
    print(f"  total tokens: {total_tokens:,} across {len(boundaries) - 1:,} conversations")
    for (src_name, lang), n in sorted(per_pair.items()):
        print(f"    {src_name} {lang}: {n:,} tokens")

    print(f"[sft-prepare] split: val_fraction={args.val_fraction}")
    train_n, val_n = split_at_boundary(
        train_ids, train_mask, val_ids, val_mask, boundaries, args.val_fraction,
    )
    print(f"  train: {train_n:,} tokens")
    print(f"  val:   {val_n:,} tokens")

    print("[sft-prepare] writing manifest")
    manifest_path = write_manifest(
        out, alloc, list(alloc), train_n, val_n, per_pair, args.langs, vocab_size,
    )
    print(f"  wrote {manifest_path}")
    print("[sft-prepare] done")


if __name__ == "__main__":
    main()
