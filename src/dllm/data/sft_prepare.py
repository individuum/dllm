"""EuroAgent SFT corpus prep — DE + EN, agentic + tool-calling.

Sister script to `dllm.data.prepare`. Where `prepare` builds the pretraining
corpus (5 B tokens, raw text), this builds the post-training corpus:
multi-turn conversations with structured tool calls, rendered to our canonical
ChatML schema (see `dllm.data.sft_format`), tokenized with the **same**
tokenizer that pretrained the base model (no separate BPE training).

Outputs under data/cache/sft/:
    sft_train.bin       uint16 token IDs (same vocab as train.bin)
    sft_train_mask.bin  uint8 loss-target flags, parallel to sft_train.bin
    sft_val.bin         uint16 val tokens (conversation-aligned split)
    sft_val_mask.bin    uint8 val loss-target flags
    manifest.json       per-source license / count / task-type provenance

Loss mask convention: mask[i] == 1 iff token i was generated by the assistant
(including the closing <|im_end|>). The loader is responsible for applying
the X→Y shift; the on-disk mask is *not* pre-shifted.

Compliance: each source's license is propagated to the manifest verbatim,
satisfying EU AI Act Art. 53 disclosure for SFT data the same way the
pretraining manifest does for raw text.

Requires the [data] extras (datasets + tokenizers).
"""
