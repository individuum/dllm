def sha256_of_file(path: Path, chunk: int = 8 * 1024 * 1024) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            buf = f.read(chunk)
            if not buf:
                break
            h.update(buf)
    return h.hexdigest()


def write_manifest(
    out_dir: Path,
    alloc: dict[str, dict[str, int]],
    used_sources: list[str],
    train_tokens: int,
    val_tokens: int,
    per_source_lang_tokens: dict[tuple[str, str], int],
    langs: list[str],
    vocab_size: int,
) -> Path:
    src_meta = []
    for src_name in used_sources:
        try:
            src = sources.load(src_name)
            info = src.license_info()
        except (ValueError, ImportError):
            info = {"name": src_name, "license": "unknown"}
        try:
            info["task_type"] = src.task_type()
        except Exception:  # noqa: BLE001
            info["task_type"] = "unknown"
        info["tokens_per_lang"] = {
            lang: per_source_lang_tokens.get((src_name, lang), 0) for lang in langs
        }
        info["allocated_examples_per_lang"] = alloc.get(src_name, {})
        info["fetch_date"] = date.today().isoformat()
        src_meta.append(info)

    manifest = {
        "format_version": "sft-0.0.1",
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "vocab_size": vocab_size,
        "tokenizer": "../tokenizer.json",  # relative — shared with pretraining
        "langs": langs,
        "tokens": {
            "train": train_tokens,
            "val": val_tokens,
            "total": train_tokens + val_tokens,
        },
        "splits": {
            "train": {
                "ids":  {"path": "sft_train.bin",      "tokens": train_tokens, "dtype": "uint16",
                         "sha256": sha256_of_file(out_dir / "sft_train.bin")},
                "mask": {"path": "sft_train_mask.bin", "tokens": train_tokens, "dtype": "uint8",
                         "sha256": sha256_of_file(out_dir / "sft_train_mask.bin")},
            },
            "val": {
                "ids":  {"path": "sft_val.bin",      "tokens": val_tokens, "dtype": "uint16",
                         "sha256": sha256_of_file(out_dir / "sft_val.bin")},
                "mask": {"path": "sft_val_mask.bin", "tokens": val_tokens, "dtype": "uint8",
                         "sha256": sha256_of_file(out_dir / "sft_val_mask.bin")},
            },
        },
        "sources": src_meta,
        "compliance": {
            "ai_act_art_53": (
                "Per-source license + URL + fetch date + token + example counts "
                "are recorded in this manifest, satisfying the AI Act Art. 53 "
                "'sufficiently detailed summary' requirement for SFT data."
            ),
            "dataset_licenses": (
                "All SFT sources are under EU-compatible open licenses: "
                "Apache 2.0 (Glaive v2, Hermes-FC, OASST2, Aya, hand-written) "
                "and CC-BY-4.0 (xLAM). No OpenAI-output-derived datasets "
                "(Alpaca, ShareGPT, OpenOrca-derivatives) are included — their "
                "terms-of-use would be incompatible with the GPAI copyright "
                "compliance policy."
            ),
            "gdpr": (
                "Conversational sources contain prompter-supplied text; no "
                "deliberate inclusion of personal data. Aya and OASST2 are "
                "human-contributed under consent; xLAM/Glaive/Hermes are "
                "synthetic. Hand-written examples avoid real-person identifiers."
            ),
        },
        "loss_mask_convention": (
            "Each *_mask.bin is uint8, parallel to *_train.bin / *_val.bin. "
            "mask[i] == 1 iff token i is an assistant-generated target token "
            "(including the closing <|im_end|>). The loader applies the X→Y "
            "shift; the on-disk mask is NOT pre-shifted."
        ),
        "notes": (
            "Phase 2 EuroAgent SFT v0.1. DE + EN, agentic + tool-calling. "
            "Sized ~50–80 M tokens (~1–2 % of the 5 B-token pretraining corpus). "
            "Native-DE tool-calling coverage is the weakest spot — primarily "
            "hand_written + OASST2 — and is a candidate for translation-augmented "
            "expansion once a high-quality DE-MT pipeline is online."
        ),
    }
    path = out_dir / "manifest.json"
    path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    return path


