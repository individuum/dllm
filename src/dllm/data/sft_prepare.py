EOT_TOKEN = "<|endoftext|>"
DEFAULT_LANGS = ["de", "en"]


# Per-source per-lang **example-count** budgets (not chars — SFT is small).
# Designed for ~65k conversations ≈ 50–80M tokens, plausible 1–5 % of the
# 5 B-token pretraining corpus. Operators can override via --alloc.
#
# xLAM (Salesforce/xlam-function-calling-60k) is **gated on HuggingFace** and
# is NOT in the default mix — request access first, then add it via
# `--sources xlam <other sources>`. Glaive v2 + Hermes-FC together already
# exceed xLAM's example count for EN tool-call coverage.
DEFAULT_ALLOC_COUNT = {
    "glaive_v2":         {"en": 25_000},
    "glaive_v2_de":      {"de": 25_000},  # produced offline by scripts/translate_glaive_to_de.py
    "hermes_fc":         {"en": 15_000},
    "oasst2":            {"en":  8_000, "de": 5_000},
    "aya":               {"en":  5_000, "de": 5_000},
    "germanrag":         {"de":  5_000},  # ~3k available; primary native-DE agentic
    "avemio_german_rag": {"de": 15_000},  # native-DE RAG + agentic + FC selection (MIT)
    "hand_written":      {"en":  1_000, "de": 1_000},
}


def cache_dir() -> Path:
    here = Path(__file__).resolve().parent
    out = here.parent.parent.parent / "data" / "cache" / "sft"
    out.mkdir(parents=True, exist_ok=True)
    return out


def pretrain_tokenizer_path() -> Path:
    """SFT reuses the BPE trained for pretraining — same vocab IDs, same
    embedding table on the base model."""
    here = Path(__file__).resolve().parent
    return here.parent.parent.parent / "data" / "cache" / "tokenizer.json"


# ---------------------------------------------------------------------------
# Producer threads — one per (source, lang) pair, like prepare.py
# ---------------------------------------------------------------------------


def _parallel_producers(
    alloc: dict[str, dict[str, int]],
    langs: list[str],
    out_q: _queue.Queue,
    sentinel,
) -> list[threading.Thread]:
    pairs: list[tuple[str, str, int]] = []
    for src_name, lang_budgets in alloc.items():
        try:
            src = sources.load(src_name)
        except ValueError:
            continue
        for lang, budget in lang_budgets.items():
            if lang not in langs:
                continue
            if lang not in src.supported_langs():
                continue
            if budget <= 0:
                continue
            pairs.append((src_name, lang, budget))

    def fetch(src_name: str, lang: str, budget: int) -> None:
        try:
            src = sources.load(src_name)
            for conv in src.iter_examples(lang, budget):
                out_q.put((src_name, lang, conv))
        except Exception as e:  # noqa: BLE001
            print(f"    [warn] fetcher {src_name}/{lang} died: {e}")
        finally:
            out_q.put(sentinel)

    threads: list[threading.Thread] = []
    for src_name, lang, budget in pairs:
        t = threading.Thread(
            target=fetch,
            args=(src_name, lang, budget),
            daemon=True,
            name=f"sft-fetch-{src_name}-{lang}",
        )
        t.start()
        threads.append(t)
    return threads


# ---------------------------------------------------------------------------
# Tokenization — render Conversation, encode_batch all segments
# ---------------------------------------------------------------------------


def _encode_conversation_batch(
    convs_meta: list[tuple[str, str, Conversation]],
    tokenizer,
) -> list[tuple[str, str, list[int], list[int]]]:
    """Batch-tokenize a group of conversations.

    Returns one (src_name, lang, ids, mask) per input conv. We flatten all
    segments across the batch into one encode_batch call so the Rust impl
    can parallelize maximally; then re-emit per-conversation.
    """
    if not convs_meta:
        return []

    flat_texts: list[str] = []
    flat_targets: list[int] = []
    # Per-conv slice indices into flat_texts
    boundaries: list[int] = [0]

    for _, _, conv in convs_meta:
        segs = render_chatml_with_mask(conv)
        for text, is_target in segs:
            flat_texts.append(text)
            flat_targets.append(1 if is_target else 0)
        boundaries.append(len(flat_texts))

    encodings = tokenizer.encode_batch(flat_texts)

    out: list[tuple[str, str, list[int], list[int]]] = []
    for i, (src_name, lang, _) in enumerate(convs_meta):
        start, end = boundaries[i], boundaries[i + 1]
        ids: list[int] = []
        mask: list[int] = []
        for j in range(start, end):
            seg_ids = encodings[j].ids
            ids.extend(seg_ids)
            mask.extend([flat_targets[j]] * len(seg_ids))
        out.append((src_name, lang, ids, mask))
    return out


# ---------------------------------------------------------------------------
# Streaming writer with parallel ids + mask + conversation boundaries
# ---------------------------------------------------------------------------


class DualShardWriter:
    """Writes paired (ids: uint16, mask: uint8) streams to disk.

    Buffers in memory for ~50 M tokens (~150 MB combined) before flushing.
    Tracks conversation boundary positions so train/val can be split at a
    boundary, never mid-conversation.
    """

    def __init__(self, ids_path: Path, mask_path: Path, flush_tokens: int = 50_000_000) -> None:
        self.ids_path = ids_path
        self.mask_path = mask_path
        self._ids = np.empty(flush_tokens, dtype=np.uint16)
        self._mask = np.empty(flush_tokens, dtype=np.uint8)
        self._idx = 0
        self._cap = flush_tokens
        self._total = 0
        self._boundaries: list[int] = [0]  # cumulative token positions
        self._ids_fp = ids_path.open("wb")
        self._mask_fp = mask_path.open("wb")

    def write_conv(self, ids: list[int], mask: list[int]) -> None:
        assert len(ids) == len(mask), (len(ids), len(mask))
        i = 0
        while i < len(ids):
            room = self._cap - self._idx
            take = min(room, len(ids) - i)
            self._ids[self._idx : self._idx + take] = ids[i : i + take]
            self._mask[self._idx : self._idx + take] = mask[i : i + take]
            self._idx += take
            i += take
            if self._idx == self._cap:
                self._flush()
        # Record cumulative token position where this conversation ended.
        self._boundaries.append(self._total + self._idx)

    def _flush(self) -> None:
        if self._idx == 0:
            return
        self._ids_fp.write(self._ids[: self._idx].tobytes())
        self._mask_fp.write(self._mask[: self._idx].tobytes())
        self._total += self._idx
        self._idx = 0

    def close(self) -> tuple[int, list[int]]:
        self._flush()
        self._ids_fp.close()
        self._mask_fp.close()
        return self._total, list(self._boundaries)


def stream_tokenize_to_disk(
    alloc: dict[str, dict[str, int]],
    langs: list[str],
    tokenizer,
    ids_path: Path,
    mask_path: Path,
    batch_size: int = 64,
    queue_size: int = 256,
) -> tuple[int, dict[tuple[str, str], int], list[int]]:
    """Run producers → encode_batch → DualShardWriter end to end.

    Returns (total_tokens, per_(src,lang)_token_count, conversation_boundaries).
    Boundaries are token positions where each conversation ends; useful for
    splitting train/val at a boundary.
    """
    SENTINEL = object()
    conv_q: _queue.Queue = _queue.Queue(maxsize=queue_size)

    producers = _parallel_producers(alloc, langs, conv_q, SENTINEL)
    n_producers = len(producers)

    writer = DualShardWriter(ids_path, mask_path)
    counts: dict[tuple[str, str], int] = {}
    n_convs = 0
    last_print = 0

    sentinels_seen = 0
    batch: list[tuple[str, str, Conversation]] = []

    def drain_batch():
        nonlocal n_convs, last_print
        if not batch:
            return
        encoded = _encode_conversation_batch(batch, tokenizer)
        for src_name, lang, ids, mask in encoded:
            # Append EOT between conversations as a non-target separator.
            eot_id = tokenizer.token_to_id(EOT_TOKEN)
            assert eot_id is not None, f"{EOT_TOKEN!r} missing from tokenizer vocab"
            ids = ids + [eot_id]
            mask = mask + [0]
            writer.write_conv(ids, mask)
            counts[(src_name, lang)] = counts.get((src_name, lang), 0) + len(ids)
            n_convs += 1
        batch.clear()
        cur = writer._total + writer._idx
        if cur - last_print >= 10_000_000:
            print(f"    [sft tokenize] {n_convs:,} convs, {cur / 1e6:.1f} M tokens")
            last_print = cur

    while sentinels_seen < n_producers:
        item = conv_q.get()
        if item is SENTINEL:
            sentinels_seen += 1
            continue
        batch.append(item)
        if len(batch) >= batch_size:
            drain_batch()
    drain_batch()

    for t in producers:
        t.join(timeout=2.0)

    total, boundaries = writer.close()
    return total, counts, boundaries


# ---------------------------------------------------------------------------
# Train/val split at a conversation boundary
# ---------------------------------------------------------------------------


def split_at_boundary(
    train_ids: Path,
    train_mask: Path,
    val_ids: Path,
    val_mask: Path,
    boundaries: list[int],
    val_fraction: float = 0.02,
) -> tuple[int, int]:
    """Split (ids, mask) at the conv boundary closest to (1 - val_fraction).

    Never splits mid-conversation — keeps every conversation atomic on
    whichever side it lands. Returns (train_tokens, val_tokens).
    """
    total = boundaries[-1] if boundaries else 0
    if total == 0:
        return 0, 0

    target = int(total * (1 - val_fraction))
    # boundaries[0] = 0; pick the boundary closest to target (but never the very
    # first, which would put all data in val).
    candidates = boundaries[1:]
    if not candidates:
        return total, 0
    split_pos = min(candidates, key=lambda p: abs(p - target))
    # Guard against degenerate edges (all in train, all in val).
    split_pos = max(1, min(total - 1, split_pos)) if total > 1 else total

    ids_arr = np.memmap(train_ids, dtype=np.uint16, mode="r")
    mask_arr = np.memmap(train_mask, dtype=np.uint8, mode="r")
    val_ids_slice = np.array(ids_arr[split_pos:], dtype=np.uint16)
    val_mask_slice = np.array(mask_arr[split_pos:], dtype=np.uint8)
    del ids_arr, mask_arr

    val_ids.write_bytes(val_ids_slice.tobytes())
    val_mask.write_bytes(val_mask_slice.tobytes())

    # Truncate train files to split_pos.
    with open(train_ids, "r+b") as f:
        f.truncate(split_pos * 2)  # uint16
    with open(train_mask, "r+b") as f:
        f.truncate(split_pos)  # uint8

    return split_pos, total - split_pos


